from django.conf import settings
from django.db import models
from django.db.models import Q


class Ticket(models.Model):
    class Status(models.TextChoices):
        OPEN = "open", "Open"
        IN_PROGRESS = "in_progress", "In progress"
        RESOLVED = "resolved", "Resolved"
        CLOSED = "closed", "Closed"

    class Priority(models.TextChoices):
        LOW = "low", "Low"
        MEDIUM = "medium", "Medium"
        HIGH = "high", "High"
        URGENT = "urgent", "Urgent"

    title = models.CharField(max_length=200)
    description = models.TextField()
    status = models.CharField(max_length=20, choices=Status.choices, default=Status.OPEN)
    priority = models.CharField(max_length=10, choices=Priority.choices, default=Priority.MEDIUM)

    # PROTECT: you cannot delete a user who has created tickets (deactivate them instead).
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="tickets_created")
    # SET_NULL: deleting an agent un-assigns their tickets rather than deleting the tickets.
    assigned_to = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="tickets_assigned"
    )
    updated_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="tickets_updated"
    )

    created_at = models.DateTimeField(auto_now_add=True)  # set once on INSERT
    updated_at = models.DateTimeField(auto_now=True)  # refreshed on every save()
    closed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-created_at", "-id"]  # default ORDER BY; "-id" makes the order deterministic for pagination
        indexes = [
            models.Index(fields=["status", "priority"], name="ticket_status_priority_idx"),
            models.Index(fields=["created_by", "-created_at"], name="ticket_creator_created_idx"),
            models.Index(fields=["assigned_to", "status"], name="ticket_assignee_status_idx"),
            models.Index(fields=["-created_at"], name="ticket_created_at_idx"),
        ]
        constraints = [
            models.CheckConstraint(
                condition=Q(status__in=["open", "in_progress", "resolved", "closed"]),
                name="ticket_status_valid",
            ),
            models.CheckConstraint(
                condition=Q(priority__in=["low", "medium", "high", "urgent"]),
                name="ticket_priority_valid",
            ),
            # closed_at may only be filled in for closed tickets.
            models.CheckConstraint(
                condition=Q(closed_at__isnull=True) | Q(status="closed"),
                name="ticket_closed_at_only_when_closed",
            ),
        ]

    def __str__(self) -> str:
        return f"#{self.pk} {self.title}"


class Comment(models.Model):
    ticket = models.ForeignKey(Ticket, on_delete=models.CASCADE, related_name="comments")
    author = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="ticket_comments")
    body = models.TextField()
    is_internal = models.BooleanField(default=False, help_text="Visible to support staff only.")
    is_system = models.BooleanField(default=False, help_text="Generated by the app (assignment, status change).")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["created_at", "id"]
        indexes = [models.Index(fields=["ticket", "created_at"], name="comment_ticket_created_idx")]
        constraints = [
            models.CheckConstraint(condition=~Q(body=""), name="comment_body_not_empty"),
        ]

    def __str__(self) -> str:
        return f"Comment {self.pk} on ticket {self.ticket_id}"
